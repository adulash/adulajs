import { access, readFile, readdir, rename, writeFile, copyFile, mkdir } from 'node:fs/promises'
import { join, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { LOCAL_PACKAGES, packageArchive } from './project.mjs'

/**
 * First step of the 2.0 upgrade. Moves a 1.x application from the packages it used
 * before the AdulaJS rename to `adula` and `create-adulajs` without booting
 * AdonisJS: once the old package is gone, `node ace` cannot start until imports
 * name the new one. This file is the single allow-listed place for the retired
 * name in the creator.
 */
const RETIRED = 'kit'
const LEGACY_CORE = `@adula/${RETIRED}`
const LEGACY_CREATOR = '@adula/create-app'

/** Identifiers the 1.x public API exported, with their 2.0 names. */
export const RENAMED_IDENTIFIERS = [
  [`${capitalize(RETIRED)}Error`, 'AdulaError'],
  [`${capitalize(RETIRED)}Ability`, 'AdulaAbility'],
  [`${capitalize(RETIRED)}Actor`, 'AdulaActor'],
  [`${RETIRED.toUpperCase()}_VERSION`, 'ADULA_VERSION'],
  [`with${capitalize(RETIRED)}Database`, 'withAdulaDatabase'],
]
const LEGACY_ROUTES = `start/${RETIRED}_routes.ts`
const ROUTES = 'start/adula_routes.ts'
const LEGACY_LOCK_KEY = `${RETIRED}Compatibility`
const LEGACY_LINT_RULE = `adula/no-${RETIRED}-patching`

const SOURCE = /\.(?:[cm]?[jt]sx?|json)$/
// Dependency and VCS trees are skipped anywhere; generated output only at the application root.
const SKIPPED_ANYWHERE = new Set(['node_modules', '.git'])
const SKIPPED_AT_ROOT = new Set(['build', '.adonisjs', '.adula-packages', 'tmp'])
// package.json is rewritten structurally; npm's lockfile is regenerated by the install.
const NOT_SOURCE = new Set(['package.json', 'package-lock.json'])

function capitalize(text) {
  return text.charAt(0).toUpperCase() + text.slice(1)
}

const escape = (text) => text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')

/** Rewrites one source text; returns it unchanged when nothing names 1.x. */
export function rewriteSource(text) {
  let next = text
    .replace(new RegExp(`(['"\`])${escape(LEGACY_CORE)}(?=['"\`/])`, 'g'), '$1adula')
    .replace(new RegExp(`(['"\`])${escape(LEGACY_CREATOR)}(?=['"\`])`, 'g'), '$1create-adulajs')
    .replace(new RegExp(`#start/${RETIRED}_routes\\b`, 'g'), '#start/adula_routes')
    .replaceAll(LEGACY_LINT_RULE, 'adula/no-core-patching')
  for (const [from, to] of RENAMED_IDENTIFIERS)
    next = next.replace(new RegExp(`\\b${from}\\b`, 'g'), to)
  return next
}

/** Moves the 1.x dependencies to `adula`, `@adula/ui` and `create-adulajs` at `version`. */
export function rewriteManifest(pkg, version, local = {}) {
  const next = structuredClone(pkg)
  for (const kind of ['dependencies', 'devDependencies']) {
    const deps = next[kind]
    if (!deps) continue
    if (deps[LEGACY_CORE]) {
      delete deps[LEGACY_CORE]
      deps.adula = local.adula ?? `^${version}`
    }
    if (deps['@adula/ui']) deps['@adula/ui'] = local['@adula/ui'] ?? `^${version}`
    if (deps[LEGACY_CREATOR]) {
      delete deps[LEGACY_CREATOR]
      deps['create-adulajs'] = `^${version}`
    }
    next[kind] = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)))
  }
  return next
}

async function exists(path) {
  return access(path).then(
    () => true,
    () => false
  )
}

async function* sources(root, directory = root) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink() || SKIPPED_ANYWHERE.has(entry.name)) continue
    if (directory === root && SKIPPED_AT_ROOT.has(entry.name)) continue
    const path = join(directory, entry.name)
    if (entry.isDirectory()) yield* sources(root, path)
    else if (SOURCE.test(entry.name) && !NOT_SOURCE.has(entry.name)) yield path
  }
}

/** True when git tracks the application (at any depth of a repository) and it has changes. */
function gitIsDirty(root) {
  const status = spawnSync('git', ['status', '--porcelain', '--', '.'], {
    cwd: root,
    encoding: 'utf8',
  })
  return status.status === 0 && status.stdout.trim().length > 0
}

/** The package manager the application already uses, from its lockfile. */
export async function lockedManager(root) {
  if (await exists(join(root, 'pnpm-lock.yaml'))) return 'pnpm'
  if (await exists(join(root, 'package-lock.json'))) return 'npm'
  if (await exists(join(root, 'yarn.lock'))) return 'yarn'
  return 'pnpm'
}

/**
 * Upgrades the application at `root` in place. `packages` points at a directory of
 * local archives (as for create); otherwise the registry versions are used.
 * Returns the relative paths it changed.
 * @param {string} root
 * @param {{ version: string, packages?: string, force?: boolean }} options
 */
export async function upgradeApplication(root, { version, packages, force = false }) {
  const manifestPath = join(root, 'package.json')
  if (!(await exists(manifestPath))) throw new Error(`No package.json in ${root}`)
  const pkg = JSON.parse(await readFile(manifestPath, 'utf8'))
  const deps = { ...pkg.dependencies, ...pkg.devDependencies }
  if (!deps[LEGACY_CORE] && !deps.adula)
    throw new Error(`${root} is not an AdulaJS application: neither adula nor ${LEGACY_CORE} is a dependency`)
  if (!deps[LEGACY_CORE]) return []
  if (!force && gitIsDirty(root))
    throw new Error('Commit or stash your changes first, or pass --force')

  const changed = []
  const local = {}
  if (packages) {
    await mkdir(join(root, '.adula-packages'), { recursive: true })
    for (const name of LOCAL_PACKAGES) {
      const archive = packageArchive(name)
      await copyFile(resolve(packages, packageArchive(name, version)), join(root, '.adula-packages', archive))
      local[name] = `file:.adula-packages/${archive}`
    }
  }
  await writeFile(manifestPath, `${JSON.stringify(rewriteManifest(pkg, version, local), null, 2)}\n`)
  changed.push('package.json')

  for await (const path of sources(root)) {
    const text = await readFile(path, 'utf8')
    const next = rewriteSource(text)
    if (next === text) continue
    await writeFile(path, next)
    changed.push(relative(root, path).replaceAll('\\', '/'))
  }
  const lockPath = join(root, 'ui.lock.json')
  if (await exists(lockPath)) {
    const lock = JSON.parse(await readFile(lockPath, 'utf8'))
    if (LEGACY_LOCK_KEY in lock) {
      const renamed = Object.fromEntries(
        Object.entries(lock).map(([key, value]) => [key === LEGACY_LOCK_KEY ? 'adulaCompatibility' : key, value])
      )
      await writeFile(lockPath, `${JSON.stringify(renamed, null, 2)}\n`)
      changed.push('ui.lock.json')
    }
  }
  if ((await exists(join(root, LEGACY_ROUTES))) && !(await exists(join(root, ROUTES)))) {
    await rename(join(root, LEGACY_ROUTES), join(root, ROUTES))
    changed.push(`${LEGACY_ROUTES} -> ${ROUTES}`)
  }
  return changed
}
